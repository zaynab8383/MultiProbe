/* ------------------------------------------------------------------ */
typedef enum { RD_PB1 = 0, RD_PA6, RD_PA2, RD_PC1, RD_PC4, RD_COUNT } ReadSrc_t;
#define RD_DEFAULT_FOR_PROBE1   RD_PB1
