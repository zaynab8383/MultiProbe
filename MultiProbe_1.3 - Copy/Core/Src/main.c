/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */
  LCD_MPU_Config();
  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* Configure the peripherals common clocks */
  PeriphCommonClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_ADC2_Init();
  MX_DAC1_Init();
  MX_FMC_Init();
  (void)XIP_Init();
  (void)ExtData_Sync();   /* programs the QSPI data staged by the debugger (first run only) */   /* maps the QSPI flash at 0x90000000 (constant data lives there) - replaces HAL OCTOSPI init */
  MX_OPAMP1_Init();
  MX_SPI3_Init();
  MX_TIM1_Init();
  MX_TIM15_Init();
  MX_UART4_Init();
  MX_USB_OTG_HS_PCD_Init();
  /* USER CODE BEGIN 2 */
  Keypad_Init();
  StatusBar_Init();
  GPIO_InitTypeDef gi = {0};
  gi.Pin   = GPIO_PIN_8;
  gi.Mode  = GPIO_MODE_OUTPUT_PP;
  gi.Pull  = GPIO_NOPULL;
  gi.Speed = GPIO_SPEED_FREQ_LOW;
  HAL_GPIO_Init(GPIOC, &gi);

  LCD_Init();
  Adc_Init();
  Probe_Init();            /* همه‌ی OE ها HIGH (خاموش)، سوئیچ‌ها بیکار، PWM قطع */
  Adc_SelfTest();
  if (g_vdda > 3.0f && g_vdda < 3.6f) {
      Beep(1);      /* سالم */
  } else {
      Beep(3);      /* مشکل */
  }

  /* Make sure the logo is stored in IC1 (W25Q64), then show it from there.
   * Debug colors if something fails:
   *   YELLOW  = IC1 not detected (OSPI / wiring / ID != EF 40 17)
   *   MAGENTA = erase/program/verify of IC1 failed
   *   CYAN    = reading the image back from IC1 failed
   */
  LCD_FillColor(LCD_COLOR_RED);

  switch (Image_EnsureInFlash())
  {
  case IMG_OK_ALREADY:
  case IMG_OK_PROGRAMMED:
      if (LCD_LoadImageToRam() != HAL_OK || LCD_DrawImageFromRam() != HAL_OK)
      {
          LCD_FillColor(LCD_COLOR_CYAN);
          HAL_Delay(2500);
      }
      else
      {
          Video_Boot();    /* mailbox + پنجره‌ی کوتاه آپلود ویدیو از USB؛ بعدش برمی‌گرده */
          HAL_Delay(800);  /* لوگو یه لحظه دیده بشه */
      }
      break;
  default:
      HAL_Delay(2500);     /* رنگ خطا دیده بشه */
      break;
  }

  /* منوی اصلی */
  LCD_FillColor(LCD_COLOR_BLACK);
  StatusBar_Init();
  Carousel_Init();
  /* USER CODE END 2 */
#if LCD_FPS_BENCHMARK
  /* Redraws the cached image 100 times and stores the result in
   * g_lcd_fps_x10 (FPS * 10). Put a breakpoint on the while(1) below
   * and watch the variable in the debugger. */
  {
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CYCCNT = 0U;
    DWT->CTRL  |= DWT_CTRL_CYCCNTENA_Msk;

    const uint32_t frames = 100U;
    uint32_t t0 = DWT->CYCCNT;
    for (uint32_t f = 0U; f < frames; f++)
    {
      (void)LCD_DrawImageFromRam();
    }
    uint32_t cycles = DWT->CYCCNT - t0;   /* fine for < ~10 s at 400 MHz */
    g_lcd_fps_x10 = (uint32_t)(((uint64_t)frames * SystemCoreClock * 10U) / cycles);
  }
#endif
  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    MenuInput_t in = Keypad_Poll();
    if (in != MENU_INPUT_NONE)
    {
      Carousel_HandleInput(in);   /* LEFT/RIGHT = صفحه‌ی بعد/قبل ، ENTER = ورود به صفحه */
    }
    StatusBar_Task();

    static uint32_t lastLed = 0U;
    if ((HAL_GetTick() - lastLed) >= 150U)
    {
      lastLed = HAL_GetTick();
      LEDs_UpdateVoltage(Adc_GetVin());
    }
    Carousel_Draw();
  }
  /* USER CODE END 3 */
}

